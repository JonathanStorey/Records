import CloudKit

/// A value type that Records stores as a `CKRecord`.
///
/// Adopt it with the `@Record` macro rather than by hand. The `id` becomes the record name,
/// so it is never written as a field. Its type, such as `Note.ID`, names its record, so one
/// record's ID can't stand in for another's.
public protocol Record: Identifiable where ID == RecordID<Self> {
    /// The CloudKit record type. `@Record` sets it to the type's name, or to the name it is given.
    static var recordType: CKRecord.RecordType { get }

    /// The type's fields and references, which the container builds its tables from.
    /// Generated by `@Record`.
    static var schema: RecordSchema { get }

    /// What each property is saved as, by its key path: the column of a stored field, with
    /// `\.id` mapped to the record's name, or the property name of a `@Reference`. Generated by
    /// `@Record`, and used to turn predicates into SQL.
    static var keyPaths: [PartialKeyPath<Self>: String] { get }

    /// Reads the record's `id`, every other stored property, and its `@Timestamped` dates from
    /// its database row. Generated by `@Record`.
    init(from row: RecordRow) throws(CKRecordDecodingError)

    /// Writes every stored property except `id` into `row`, keyed by field key. Generated by
    /// `@Record`.
    func encodeFields(into row: inout RecordRow)

    /// Every `@Reference` that writes links, with its current targets.
    /// `@Reference(from:)` properties write none, so they are left out. Generated by `@Record`.
    var referenceStates: [ReferenceState] { get }

    /// Sets the `@Reference` named `property` to the targets with IDs `targets`, as read from
    /// storage. When the property holds records and `depth` is at least 1, reads the targets
    /// `graph` holds with `depth - 1`. Generated by `@Record`.
    mutating func loadReference(_ property: String, to targets: [UUID], from graph: RecordGraph, depth: Int) throws

    /// Every `@Asset`, with its current ID and file. Generated by `@Record`.
    var assetStates: [AssetState] { get }

    /// Sets the `@Asset` stored under `property` as read from its link. Generated by `@Record`.
    mutating func loadAsset(_ property: String, id: UUID?, file: URL?)
}

/// Records without references or assets.
extension Record {
    public static var keyPaths: [PartialKeyPath<Self>: String] { [:] }
    public var assetStates: [AssetState] { [] }
    public mutating func loadAsset(_ property: String, id: UUID?, file: URL?) {}
    public var referenceStates: [ReferenceState] { [] }
    public mutating func loadReference(_ property: String, to targets: [UUID], from graph: RecordGraph, depth: Int) throws {}
}
